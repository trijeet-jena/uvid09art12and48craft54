/* UVID — embed real product photos into the bundle.
   Scans assets/*.{jpg,jpeg,png,webp}; filename (without extension) = product id.
   Writes data/product-images.js which must be loaded BEFORE data/products.js. */
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const assetsDir = path.join(root, "assets");
const outFile = path.join(root, "data", "product-images.js");

const MIME = {
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".png": "image/png",
  ".webp": "image/webp",
};

const map = {};
if (fs.existsSync(assetsDir)) {
  for (const f of fs.readdirSync(assetsDir).sort()) {
    const ext = path.extname(f).toLowerCase();
    if (!MIME[ext]) continue;
    const id = path.basename(f, ext);
    const b64 = fs.readFileSync(path.join(assetsDir, f)).toString("base64");
    map[id] = "data:" + MIME[ext] + ";base64," + b64;
    console.log(id, "<-", f, "(" + (b64.length / 1024).toFixed(1) + " KB base64)");
  }
}

const banner =
  "/* UVID - real product photos as data-URIs.\n" +
  "   GENERATED by tools/embed-images.js - put a photo in assets/<product-id>.jpg and re-run it. */\n" +
  '(function () {\n  "use strict";\n';

fs.writeFileSync(outFile, banner + "  window.UVID_IMG = " + JSON.stringify(map) + ";\n})();\n");
console.log(
  "Wrote data/product-images.js with",
  Object.keys(map).length,
  "photo(s) — total",
  ((banner.length + JSON.stringify(map).length) / 1024).toFixed(1) + " KB"
);
